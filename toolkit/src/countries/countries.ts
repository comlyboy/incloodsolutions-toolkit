/**
 * A country, how to call it, its timezones and the currency it uses. Built from the ISO 4217 currency list (SIX
 * Group, published 2026-09-17) joined to a country code list by name. Currency symbols come from the Unicode CLDR
 * data built into JavaScript, in the country's own regional format where English has none (Kenya: "Ksh"). Phone
 * codes come from Google's libphonenumber data, timezones from the countries-and-timezones data (IANA).
 */
export interface ICountry {
	name: string;
	/** ISO 3166 two-letter code, as in "NG". */
	alpha2Code: string;
	/** Flag emoji, as in "🇳🇬". Built from the alpha-2 code; Windows browsers show the letters ("NG") instead of a flag. */
	flag: string;
	/** ISO 3166 three-letter code, as in "NGA". Kosovo's "XKX" is not an ISO code: ISO has not assigned one. */
	alpha3Code: string;
	/** ISO 3166 numeric country code, three digits, as in "566". */
	numericCode: string;
	/** International calling code, as in "+234". Null for places without one (Antarctica, uninhabited islands). */
	phoneCode: string | null;
	/**
	 * IANA timezones in use in the country, east to west, as in ["Africa/Lagos"]; several for countries such as
	 * the US or Russia. Only names are kept: offsets change with daylight saving, so work them out with Intl.
	 */
	timezones: readonly string[];
	/** ISO 4217 code of the currency in everyday use, as in "NGN". Null where there is no official currency. */
	currencyCode: string | null;
	currencyName: string | null;
	/** As in "₦", "$", "Ksh". The code itself where no symbol is used, as for "CHF". */
	currencySymbol: string | null;
	/** ISO 4217 numeric currency code, as in "566" for NGN or "978" for EUR. */
	currencyNumericCode: string | null;
	/**
	 * Decimal places of the currency's smallest unit: 2 for most (store amounts x 100), 0 for JPY (x 1),
	 * 3 for KWD (x 1000).
	 */
	minorUnits: number | null;
	/** Other currencies the country also uses officially, as in ["USD"] for Panama. */
	otherCurrencyCodes: readonly string[];
}

/** Identity helper whose `const` type parameter keeps every code as a string literal (and not just `string`). */
function defineCountries<const TCountries extends readonly ICountry[]>(
	list: TCountries,
): TCountries {
	return list;
}

