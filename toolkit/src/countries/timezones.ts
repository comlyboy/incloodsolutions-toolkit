/**
 * An IANA timezone and the countries that use it. Built from the countries-and-timezones package
 * (IANA tz database), including deprecated alias names such as "Africa/Douala".
 */
export interface ITimezone {
	/** IANA name, as in "Africa/Lagos". */
	name: string;
	/**
	 * ISO 3166 alpha-2 codes of the countries using this timezone. The first is the zone's main country,
	 * so "Africa/Lagos" lists "NG" before Cameroon, Gabon and the others that share it.
	 */
	countries: string[];
	/** Standard-time offset from UTC in minutes, as in 60 for "+01:00". */
	utcOffset: number;
	/** Daylight-saving offset from UTC in minutes. Equal to `utcOffset` where there is no daylight saving. */
	dstOffset: number;
	/** The canonical zone this name is an alias of ("Africa/Lagos" for "Africa/Douala"), else null. */
	aliasOf: string | null;
}

